'use strict';

/* Publish-time driver. Parses every detection file and writes one
   _data/detection_manifests.yml keyed by slug.

   One file rather than 56 keeps the output reviewable as a single git diff, so
   a lost rule or a changed tier shows up before publication rather than on the
   live page.

   Exit codes match the other gates: 0 PASS, 1 FAIL, 2 NOT CHECKED. A file that
   cannot be read is NOT CHECKED with the reason, never counted as a pass, and a
   run that generated nothing says so. */

var fs = require('node:fs');
var path = require('node:path');

var P = null, DEPS_REASON = null;
try {
  P = require('./lib/parse-detections.js');
  if (!P || typeof P.parse !== 'function') throw new Error('parse-detections.js exports no parse');
} catch (e) {
  DEPS_REASON = 'parser did not load: ' + String((e && e.message) || e).split('\n')[0];
}

var ROOT = path.join(__dirname, '..', '..');
var SRC_DIR = path.join(ROOT, 'hunting-detections');
var OUT = path.join(ROOT, '_data', 'detection_manifests.yml');

function yamlEscape(s) {
  return '"' + String(s).replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
}

/* Hand-written emitter rather than a YAML dependency, matching the site repo's
   existing no-dependency stance. Only the shapes below are ever emitted, and
   Step 4 of the plan reads the file back and asserts its counts, so a shape
   this cannot emit correctly surfaces there rather than on the page. */
function toYaml(bySlug) {
  var out = ['# Generated by tools/report-tooling/generate-detection-manifests.js',
             '# Do not edit by hand. Regenerate after any change to hunting-detections/.',
             ''];
  Object.keys(bySlug).sort().forEach(function (slug) {
    out.push(slug + ':');
    bySlug[slug].forEach(function (r) {
      out.push('  - name: ' + yamlEscape(r.name));
      out.push('    engine: ' + r.engine);
      out.push('    tier: ' + r.tier);
      if (r.cross_referenced) {
        // No fence of its own: its body lives inside an earlier bundle. Carried
        // so the reader still sees the rule, with the picker showing it as
        // present but not separately selectable.
        out.push('    cross_referenced: true');
      } else {
        out.push('    fence: ' + r.fence);
        out.push('    hash: ' + yamlEscape(r.hash));
        out.push('    head: ' + yamlEscape(r.head));
      }
      if (r.robustness !== null && !isNaN(r.robustness)) out.push('    robustness: ' + r.robustness);
      if (r.confidence) out.push('    confidence: ' + yamlEscape(r.confidence));
      if (r.attack && r.attack.length) out.push('    attack: [' + r.attack.join(', ') + ']');
    });
  });
  return out.join('\n') + '\n';
}

function run(opts) {
  opts = opts || {};
  if (DEPS_REASON) {
    return { status: 'NOT CHECKED', reason: DEPS_REASON, files: 0, rules: 0, xref: 0, problems: [] };
  }

  var files;
  try {
    files = fs.readdirSync(SRC_DIR).filter(function (f) { return /-detections\.md$/.test(f); }).sort();
  } catch (e) {
    return { status: 'NOT CHECKED', reason: 'cannot read ' + SRC_DIR + ': ' + e.message,
             files: 0, rules: 0, xref: 0, problems: [] };
  }
  if (!files.length) {
    return { status: 'NOT CHECKED', reason: 'no detection files found in ' + SRC_DIR,
             files: 0, rules: 0, xref: 0, problems: [] };
  }

  var bySlug = {}, problems = [], rules = 0, xref = 0, skipped = 0;
  files.forEach(function (f) {
    var slug = f.replace(/\.md$/, '');
    var src;
    try { src = fs.readFileSync(path.join(SRC_DIR, f), 'utf8'); }
    catch (e) { problems.push(f + ': NOT CHECKED, ' + e.message); skipped++; return; }

    var r = P.parse(src, slug);

    r.unresolved.forEach(function (u) {
      problems.push(f + ' line ' + u.line + ': "' + u.name + '" ' + u.reason);
    });

    /* The invariant with teeth. Every **Tier:** line in the file must be
       accounted for by exactly one entry, and an entry may consume several when
       its fence bundles a correlation rule with its base rules. Counting
       entries instead of lines would let a tier line vanish inside a bundle
       without anything noticing, which is the silent-shrink failure this gate
       exists to prevent. Headings carrying no Tier are prose and consume none. */
    var declared = (src.match(/^\*\*Tier:\*\*/gm) || []).length;
    var consumed = 0;
    r.rules.forEach(function (x) { consumed += x.tier_raw.length; });
    r.unresolved.forEach(function (x) { consumed += (x.tier_raw || []).length; });
    if (consumed !== declared) {
      problems.push(f + ': accounted for ' + consumed + ' Tier lines but the file declares ' +
        declared + '. A rule was dropped or a tier line was read twice.');
    }

    /* Two rules on one page with identical bodies would make the picker's
       verification unable to tell them apart, and is almost certainly a
       duplicated rule in the file. Reported rather than tolerated. */
    var seen = {};
    r.rules.forEach(function (x) {
      if (!x.hash) return;
      if (seen[x.hash]) {
        problems.push(f + ': "' + x.name + '" has the same body as "' + seen[x.hash] + '"');
      } else {
        seen[x.hash] = x.name;
      }
    });

    bySlug[slug] = r.rules;
    rules += r.rules.length;
    r.rules.forEach(function (x) { if (x.cross_referenced) xref++; });
  });

  /* Serialised once and both written and returned, so the staleness check in
     lib/check-detection-manifest.js compares against the same text the writer
     produces. A second serialisation would be a second implementation of one
     rule, and those drift silently. */
  var text = toYaml(bySlug);

  if (!opts.dryRun) {
    fs.writeFileSync(OUT, text, 'utf8');
  }

  return {
    status: problems.length ? 'FAIL' : (skipped ? 'NOT CHECKED' : 'PASS'),
    files: files.length, rules: rules, xref: xref, slugs: Object.keys(bySlug).length,
    problems: problems, reason: skipped ? skipped + ' file(s) could not be read' : undefined,
    yaml: text
  };
}

module.exports = { run: run, toYaml: toYaml };

if (require.main === module) {
  var dry = process.argv.indexOf('--dry-run') !== -1;
  var r = run({ dryRun: dry });
  console.log(r.status + '   ' + r.files + ' files, ' + r.rules + ' rules, ' +
    r.xref + ' cross-referenced' +
    (dry ? '   (dry run, nothing written)' : '   written to _data/detection_manifests.yml'));
  if (r.reason) console.log('  reason: ' + r.reason);
  r.problems.forEach(function (p) { console.log('  ' + p); });
  process.exit(r.status === 'PASS' ? 0 : r.status === 'FAIL' ? 1 : 2);
}
