/* ---- the render-time defang (Liquid executed) ---- */
const DEFANG = strip(read('_includes/defang-text.html')).replace(/include\.text/g, 'text');
function defangCases(cases) {
  const script = RUBY_LIQUID + '\nsrc = File.read(ENV["SRC"]); t = Liquid::Template.parse(src); JSON.parse(ENV["CASES"]).each { |x| puts JSON.generate(t.render("text" => x)) }';
  const tmp = path.join(require('node:os').tmpdir(), 'hl-defang-text-' + process.pid + '.liquid'); fs.writeFileSync(tmp, DEFANG);
  const r = cp.spawnSync('/usr/bin/ruby', ['-e', script], { encoding: 'utf8', env: Object.assign({}, process.env, { SRC: tmp, CASES: JSON.stringify(cases) }) });
  fs.unlinkSync(tmp);
  if (r.error || r.status === 3) return null;
  assert.equal(r.status, 0, r.stderr);
  return r.stdout.trim().split('\n').map((l) => JSON.parse(l));
}
test('defang-text: dotted-quad words are defanged at every dot, everything else is left as written (control: a title with no address is unchanged)', (t) => {
  const got = defangCases([
    'Sliver C2 Windows Post-Exploitation Staging, 193.233.202.17',
    'Russian Gemini CLI Credential Mill (213.165.51.115)',
    'Beacon to 8.8.8.8:53 then 10.0.0.5.',
    'Version v4.3.4.1, 300.1.1.1, 1.2.3 and 01.2.3.4 (only the first is an address)',
    'GHOST Cryptojacker Kit: Vova75Rus Supply Chain',
    ''
  ]);
  if (got === null) return t.skip('NOT CHECKED: ruby or the liquid gem is missing, so the Liquid include was not executed');
  assert.deepEqual(got, [
    'Sliver C2 Windows Post-Exploitation Staging, 193[.]233[.]202[.]17',
    'Russian Gemini CLI Credential Mill (213[.]165[.]51[.]115)',
    'Beacon to 8[.]8[.]8[.]8:53 then 10[.]0[.]0[.]5.',
    'Version v4[.]3[.]4[.]1, 300.1.1.1, 1.2.3 and 01.2.3.4 (only the first is an address)',
    'GHOST Cryptojacker Kit: Vova75Rus Supply Chain',
    ''
  ]);
});
