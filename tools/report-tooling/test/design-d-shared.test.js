  const tmp = path.join(require('node:os').tmpdir(), 'hl-epss-' + process.pid + '.liquid'); fs.writeFileSync(tmp, inc.replace(/\{%-? comment -%\}[\s\S]*?\{%-? endcomment -%\}/g, ''));
  const r = cp.spawnSync('/usr/bin/ruby', ['-e', script], { encoding: 'utf8', env: Object.assign({}, process.env, { SRC: tmp }) }); fs.unlinkSync(tmp);
  if (r.error || r.status === 3) return t.skip('NOT CHECKED: ruby or the liquid gem is missing, so the Liquid include was not executed');
